const copyPath = "node_modules/.deno/deno.lock";
const hasLockfile = Deno.statSync("deno.lock").isFile;
const hasCopy = Deno.statSync(copyPath).isFile;
console.log("deno.lock exists:", hasLockfile);
console.log("copy exists:", hasCopy);
if (hasLockfile && hasCopy) {
  const lockfile = JSON.parse(Deno.readTextFileSync("deno.lock"));
  const copy = JSON.parse(Deno.readTextFileSync(copyPath));
  console.log("copy keys:", Object.keys(copy).join(", "));
  console.log(
    "same npm packages:",
    JSON.stringify(lockfile.npm) === JSON.stringify(copy.npm),
  );
  console.log("npm packages:", Object.keys(lockfile.npm).join(", "));
}
